import { describe, it, expect, beforeEach } from "vitest";
import worker from "../index";
import { InMemorySnapshotStore } from "../store/SnapshotStore";
import {
  buildFacultyProfileSnapshot,
  runAggregationAndSnapshotSync,
  type FacultyRow,
  type RawReviewRow,
} from "../aggregation/engine";
import {
  schemaVersion,
  SCHEMA_VERSION,
  TEACHING_CONFIG,
  PROJECT_CONFIG,
  CANONICAL_REVIEW_QUESTIONS,
} from "../config/reviewQuestions";
import type { Env, ReviewSubmissionMessage } from "../types";

describe("Cloudflare Worker Shared Schemas & Contract Specification", () => {
  let mockEnv: Env;
  let inMemoryStore: InMemorySnapshotStore;

  beforeEach(() => {
    inMemoryStore = new InMemorySnapshotStore();
    mockEnv = {
      SNAPSHOT_STORE: "memory",
      READ_ONLY_MODE: "false",
      MAX_KV_WRITES_PER_RUN: "50",
      SUPABASE_URL: "https://test.supabase.co",
      REVIEWS_INGEST_SECRET: "test-secret-1234567890",
      REVIEWS_SNAPSHOTS: inMemoryStore as unknown as KVNamespace,
      amazecc_reviews_queue: {
        send: async () => {},
      } as unknown as Queue<ReviewSubmissionMessage>,
    };
  });

  describe("Schema Versioning Constants", () => {
    it("exports canonical schemaVersion strictly equal to '1.0.0'", () => {
      expect(schemaVersion).toBe("1.0.0");
      expect(SCHEMA_VERSION).toBe("1.0.0");
    });

    it("embodies schemaVersion in TEACHING_CONFIG, PROJECT_CONFIG, and CANONICAL_REVIEW_QUESTIONS", () => {
      expect(TEACHING_CONFIG.schemaVersion).toBe("1.0.0");
      expect(PROJECT_CONFIG.schemaVersion).toBe("1.0.0");
      expect(CANONICAL_REVIEW_QUESTIONS.schemaVersion).toBe("1.0.0");
    });
  });

  describe("Aggregation Engine Snapshot Contracts", () => {
    const mockFaculty: FacultyRow = {
      id: "fac-100",
      employee_id: "EMP100",
      name: "Dr. Test Professor",
      name_norm: "test professor",
      school: "SCOPE",
      designation: "Professor",
      image_url: null,
      vitfac_id: "vitfac-100",
      status: "official",
      merged_into: null,
    };

    const mockReview: RawReviewRow = {
      id: "rev-1",
      student_hash: "hash-student-1",
      faculty_id: "fac-100",
      track: "teaching",
      course_code: "CSE1001",
      semester: "FALL2026",
      project_term: null,
      verified: true,
      answers: { T_CLARITY: 5, T_DOUBTS: 4, T_ALIGN: 4, T_FAIR: 5, T_REGULAR: 5, T_ENGAGE: 4, T_MATERIAL: 4, T_AGAIN: 5 },
      tags_green: ["Explains with examples"],
      tags_red: [],
      context: {},
      grade_bucket: null,
      created_at: "2026-03-01T00:00:00.000Z",
    };

    it("includes schemaVersion '1.0.0' in buildFacultyProfileSnapshot output", () => {
      const profile = buildFacultyProfileSnapshot(mockFaculty, [mockReview]);
      expect(profile.schemaVersion).toBe("1.0.0");
      expect(profile.faculty.id).toBe("fac-100");
      expect(profile.teaching).toBeDefined();
    });

    it("includes schemaVersion '1.0.0' in catalog snapshot generated by runAggregationAndSnapshotSync", async () => {
      await runAggregationAndSnapshotSync(
        inMemoryStore,
        [mockFaculty],
        [mockReview],
        50
      );

      const catalogRaw = await inMemoryStore.get("catalog.json");
      expect(catalogRaw).not.toBeNull();
      const catalog = JSON.parse(catalogRaw!.body);
      expect(catalog.schemaVersion).toBe("1.0.0");
      expect(Array.isArray(catalog.faculty)).toBe(true);
      expect(catalog.faculty[0].id).toBe("fac-100");
    });
  });

  describe("Worker Endpoints Contract Adherence", () => {
    it("serves catalog fallback with schemaVersion '1.0.0' when uninitialized", async () => {
      const req = new Request("http://localhost/api/reviews/catalog");
      const res = await worker.fetch(req, mockEnv, {} as ExecutionContext);
      expect(res.status).toBe(200);

      const data = (await res.json()) as { schemaVersion: string; faculty: unknown[] };
      expect(data.schemaVersion).toBe("1.0.0");
      expect(Array.isArray(data.faculty)).toBe(true);
    });

    it("accepts valid Ingest submission message with schemaVersion '1.0.0'", async () => {
      const message: ReviewSubmissionMessage = {
        schemaVersion: "1.0.0",
        idempotencyKey: "key-1",
        student_hash: "hash-xyz",
        faculty_id: "fac-100",
        track: "teaching",
        verified: true,
        answers: { T_CLARITY: 5 },
        tags_green: [],
        tags_red: [],
        context: {},
        timestamp: Date.now(),
      };

      const rawBody = JSON.stringify(message);
      const timestamp = Date.now().toString();

      const enc = new TextEncoder();
      const key = await crypto.subtle.importKey(
        "raw",
        enc.encode(mockEnv.REVIEWS_INGEST_SECRET),
        { name: "HMAC", hash: "SHA-256" },
        false,
        ["sign"]
      );
      const sigBuffer = await crypto.subtle.sign(
        "HMAC",
        key,
        enc.encode(`${timestamp}.${rawBody}`)
      );
      const signature = Array.from(new Uint8Array(sigBuffer))
        .map((b) => b.toString(16).padStart(2, "0"))
        .join("");

      const req = new Request("http://localhost/internal/ingest", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "x-timestamp": timestamp,
          "x-signature": signature,
        },
        body: rawBody,
      });

      const res = await worker.fetch(req, mockEnv, {} as ExecutionContext);
      expect(res.status).toBe(202);
      const json = (await res.json()) as { success: boolean; status: string };
      expect(json.success).toBe(true);
    });
  });
});
