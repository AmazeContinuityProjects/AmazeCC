/**
 * The structured text PDF of the current plan: the **weekly curriculum** every
 * picked course expands to, plus FFCS-inator's **"Clashes With"** column.
 *
 * The curriculum section is the point of the report. A flat course list says
 * *which* courses a timetable holds; a student copying their curriculum needs
 * *when* each one meets — so every slot is expanded through the campus schema
 * (`periodsForSlot`) into day-and-clock sessions, consecutive periods of one
 * class merged into a single block, and printed one session per row, ordered
 * by day and time. Read down a day column and you have the week.
 *
 * `portraitDossier.ts` already renders jsPDF text tables (wrap, chunked rows,
 * page splits, zebra stripes); this module reuses that recipe for both tables
 * here — see `ffcsClashPairs` for the clash arithmetic and the same-code
 * rulings.
 *
 * Import-light by design: types and two pure data maps from the FFCS folder,
 * clash maths from the lib, jsPDF pulled lazily on first use so a planner
 * session that never exports a report never pays for the library.
 */
import type { jsPDF } from "jspdf";
import type { AddedCourse } from "@/components/custom/exams/FFCS/types";
import { COLOR_HEX_MAP, typeLabels } from "@/components/custom/exams/FFCS/constants";
import { getTimetableSchema } from "@/lib/campusSchema";
import { DAYS_OF_WEEK, periodsForSlot, splitSlots, type CampusSchema } from "@/lib/slots";
import { courseClashPairs, courseClashPairCount, formatMinutesOfDay, type CourseClash } from "./ffcsClashPairs";

const PAGE_W = 210;
const PAGE_H = 297;
const CONTENT_X = 18;
const CONTENT_W = PAGE_W - CONTENT_X * 2;
const CONTENT_TOP = 18;
const CONTENT_BOTTOM = 277;
const FOOTER_Y = 284;

const CREDIT_LINE = "Clash report generated by AmazeCC - amazecc.com";

/**
 * The eight columns, in millimetres.
 *
 * They sum to 171, the same usable width `portraitDossier`'s seven columns
 * occupy inside the 174-unit content box — the slack keeps the right border
 * from kissing the card edge. Every cell wraps within its own width, so a long
 * faculty list or a busy clash list flows to a second line instead of
 * overflowing.
 */
export const CLASH_REPORT_COLUMNS = [20, 40, 13, 8, 22, 20, 22, 26] as const;
export const CLASH_REPORT_HEADERS = [
  "CODE",
  "COURSE",
  "TYPE",
  "CR",
  "SLOTS",
  "VENUE",
  "FACULTY",
  "CLASHES WITH",
] as const;

const CLASH_COLUMN = 7; // index of CLASHES WITH within the row

/**
 * The seven columns of the weekly-curriculum table, in millimetres.
 *
 * Same 171-unit content width as `CLASH_REPORT_COLUMNS`; the slack shifts
 * into TITLE because a curriculum is read by course name first.
 */
export const CURRICULUM_COLUMNS = [13, 22, 12, 18, 42, 22, 42] as const;
export const CURRICULUM_HEADERS = ["DAY", "TIME", "TYPE", "COURSE", "TITLE", "VENUE", "FACULTY"] as const;

/** One class session of the week: a course meeting on a day at a clock window. */
export interface CurriculumSession {
  /** Weekday in display form, e.g. `"Mon"`. */
  day: string;
  /** Index within `DAYS_OF_WEEK`, so Monday sorts before Friday. */
  dayOrder: number;
  startMin: number;
  endMin: number;
  type: "theory" | "lab";
  code: string;
  title: string;
  faculty: string;
  venue: string;
}

/**
 * The curriculum of a plan: every picked course expanded into the day and
 * clock time it actually meets, one row per class block.
 *
 * This is the report's reason to exist. A course list says *which* courses a
 * timetable holds; a student copying their curriculum — matching it against
 * what their friends booked, or filling VTOP's preference lists by hand —
 * needs *when* each course meets. So every slot token goes through
 * `splitSlots` + `periodsForSlot` (the same lookup the clash arithmetic
 * uses, so the two sections can never disagree), and consecutive periods of
 * one class — a lab's `L1+L2` pair, back to back with only the schema's
 * five-minute recess between — merge into a single block, because that is
 * how a student experiences the class: "lab, 8:00 to 9:40".
 *
 * Ordering is day-major (Monday first), then start time, then code — read
 * top to bottom and a day's whole curriculum falls out in one column.
 * Duplicate periods (the same period named by two slot spellings, or a
 * course listed on two rows) are collapsed by key before merging.
 */
export function buildCurriculumSessions(courses: readonly AddedCourse[], schema: CampusSchema): CurriculumSession[] {
  const seen = new Set<string>();
  const blocks: CurriculumSession[] = [];

  for (const course of courses) {
    const periods = (course.slots ?? [])
      .flatMap((slot) => splitSlots(slot))
      .flatMap((slot) => periodsForSlot(schema, slot));
    for (const period of periods) {
      const key = `${course.code}|${period.day}|${period.startMin}|${period.endMin}|${period.type}`;
      if (seen.has(key)) continue;
      seen.add(key);
      blocks.push({
        day: period.day.charAt(0).toUpperCase() + period.day.slice(1),
        dayOrder: (DAYS_OF_WEEK as readonly string[]).indexOf(period.day),
        startMin: period.startMin,
        endMin: period.endMin,
        type: period.type,
        code: course.code,
        title: course.title || "",
        faculty: (course.faculty || "TBA").trim(),
        venue: (course.venue || "TBA").trim(),
      });
    }
  }

  blocks.sort(
    (a, b) =>
      a.dayOrder - b.dayOrder ||
      a.startMin - b.startMin ||
      a.code.localeCompare(b.code) ||
      a.type.localeCompare(b.type),
  );

  // Merge back-to-back periods of the same class into one block. Same course,
  // same day, same type, same faculty and venue, and at most a recess apart
  // (the schema's breaks are five minutes) — a lab pair or a double theory
  // period, never two distinct classes.
  const RECESS_MAX_MIN = 10;
  const merged: CurriculumSession[] = [];
  for (const block of blocks) {
    const prev = merged[merged.length - 1];
    if (
      prev &&
      prev.day === block.day &&
      prev.code === block.code &&
      prev.type === block.type &&
      prev.faculty === block.faculty &&
      prev.venue === block.venue &&
      block.startMin - prev.endMin <= RECESS_MAX_MIN
    ) {
      prev.endMin = Math.max(prev.endMin, block.endMin);
      continue;
    }
    merged.push({ ...block });
  }
  return merged;
}

type Palette = {
  band: string;
  surface: string;
  panel: string;
  border: string;
  text: string;
  muted: string;
  accent: string;
  accent2: string;
  soft: string;
  clash: string;
};

/** A report is a printed document; the light palette is the only one it needs. */
const THEME: Palette = {
  band: "#e8eef7",
  surface: "#ffffff",
  panel: "#f8fafc",
  border: "#cbd5e1",
  text: "#0f172a",
  muted: "#64748b",
  accent: "#2563eb",
  accent2: "#7c3aed",
  soft: "#eff6ff",
  clash: "#b91c1c",
};

function rgb(hex: string): [number, number, number] {
  const value = hex.replace("#", "");
  return [parseInt(value.slice(0, 2), 16), parseInt(value.slice(2, 4), 16), parseInt(value.slice(4, 6), 16)];
}

function color(pdf: jsPDF, method: "setTextColor" | "setDrawColor" | "setFillColor", hex: string) {
  pdf[method](...rgb(hex));
}

function wrap(pdf: jsPDF, value: string, width: number, size: number): string[] {
  pdf.setFontSize(size);
  return pdf.splitTextToSize(value || "-", width) as string[];
}

export interface ClashReportParams {
  planName: string;
  courses: readonly AddedCourse[];
  /** Defaults to the app's pinned campus schema. */
  schema?: CampusSchema;
  /** Overrides the printed generation date; defaults to now. */
  generatedAt?: Date;
  /** Overrides the summed course credits, as the dossier export allows. */
  totalCredits?: number;
}

/**
 * The `CLASHES WITH` cell: `CSE3001 (Mon 08:00, Wed 10:45); MAT2005 (Tue 08:00)`,
 * or a plain `-` when the course clashes with nothing.
 *
 * Grouped by code so two offerings never print as two names, and only the
 * start time of each clashing window is kept — the full range lives in the
 * clash arithmetic, and the cell has 26mm to make its point.
 */
export function formatClashCell(clashes: readonly CourseClash[] | undefined): string {
  if (!clashes || clashes.length === 0) return "-";
  const byCode = new Map<string, string[]>();
  for (const clash of clashes) {
    const start = clash.timeRange.split("-")[0] ?? clash.timeRange;
    const short = `${clash.day} ${start}`;
    const times = byCode.get(clash.code);
    if (!times) byCode.set(clash.code, [short]);
    else if (!times.includes(short)) times.push(short);
  }
  return [...byCode.entries()].map(([code, times]) => `${code} (${times.join(", ")})`).join("; ");
}

function addPage(pdf: jsPDF, pageNumber: number) {
  if (pageNumber > 1) pdf.addPage("a4", "portrait");
  color(pdf, "setFillColor", THEME.surface);
  pdf.rect(0, 0, PAGE_W, PAGE_H, "F");
  color(pdf, "setTextColor", THEME.muted);
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(7);
  pdf.text(CREDIT_LINE, CONTENT_X, FOOTER_Y);
  pdf.text(`Page ${pageNumber}`, PAGE_W - CONTENT_X, FOOTER_Y, { align: "right" });
}

function drawSectionTitle(pdf: jsPDF, title: string, subtitle: string, y: number): number {
  color(pdf, "setTextColor", THEME.text);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(12);
  pdf.text(title, CONTENT_X, y);
  color(pdf, "setTextColor", THEME.muted);
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(7.5);
  pdf.text(subtitle, CONTENT_X, y + 4.5);
  color(pdf, "setDrawColor", THEME.border);
  pdf.setLineWidth(0.25);
  pdf.line(CONTENT_X, y + 7, CONTENT_X + CONTENT_W, y + 7);
  return y + 12;
}

/**
 * Build the clash report as an A4 portrait PDF.
 *
 * Works for hand-built plans (which can genuinely clash) as well as generated
 * ones — generated plans come out "No clashes - all courses fit", which is the
 * generator's guarantee made visible on paper.
 */
export async function createClashReportPdf(params: ClashReportParams): Promise<ArrayBuffer> {
  const { jsPDF } = await import("jspdf");
  const schema = params.schema ?? getTimetableSchema();
  const courses = params.courses;
  const clashByCourse = courseClashPairs(courses, schema);
  const clashPairs = courseClashPairCount(courses, schema);
  const credits =
    params.totalCredits ?? courses.reduce((sum, course) => sum + (parseFloat(course.credits || "0") || 0), 0);

  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4", compress: true });
  pdf.setProperties({
    title: `${params.planName} - FFCS Clash Report`,
    subject: "Weekly curriculum and clash report",
    creator: "AmazeCC",
  });

  let pageNumber = 1;
  let y = CONTENT_TOP;
  addPage(pdf, pageNumber);
  const newPage = () => {
    pageNumber += 1;
    addPage(pdf, pageNumber);
    y = CONTENT_TOP;
  };

  // Title banner: plan name shrunk to one line where it can be, the clash
  // verdict right-aligned where a reader looks first.
  const title = params.planName || "Timetable";
  let titleSize = 16;
  let titleLines: string[] = [];
  do {
    titleLines = wrap(pdf, title, 108, titleSize);
    if (titleLines.length <= 1 || titleSize <= 9) break;
    titleSize -= 1;
  } while (titleSize >= 9);
  const titleStep = Math.max(4.8, titleSize * 0.42);
  const bannerHeight = Math.max(30, 25 + Math.max(0, titleLines.length - 1) * titleStep);
  color(pdf, "setFillColor", THEME.soft);
  color(pdf, "setDrawColor", THEME.border);
  pdf.roundedRect(CONTENT_X, y, CONTENT_W, bannerHeight, 2, 2, "FD");
  color(pdf, "setFillColor", THEME.accent);
  pdf.roundedRect(CONTENT_X + 4, y + 4, 2, bannerHeight - 8, 0.8, 0.8, "F");
  color(pdf, "setTextColor", THEME.accent);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(7);
  pdf.text("FFCS CLASH REPORT", CONTENT_X + 10, y + 8);
  color(pdf, "setTextColor", THEME.text);
  pdf.setFontSize(titleSize);
  pdf.text(titleLines, CONTENT_X + 10, y + 15.5, { lineHeightFactor: 1.05 });
  color(pdf, "setTextColor", THEME.muted);
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(7);
  const generated = (params.generatedAt ?? new Date()).toLocaleDateString();
  pdf.text(
    `Generated ${generated}  |  ${courses.length} courses  |  ${credits} credits`,
    CONTENT_X + 10,
    y + bannerHeight - 4.5,
  );
  color(pdf, "setTextColor", clashPairs > 0 ? THEME.clash : THEME.accent2);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(8);
  pdf.text(
    clashPairs > 0 ? `${clashPairs} clash${clashPairs === 1 ? "" : "es"} detected` : "No clashes - all courses fit",
    CONTENT_X + CONTENT_W - 5,
    y + 10,
    { align: "right" },
  );
  y += bannerHeight + 6;

  if (y + 28 > CONTENT_BOTTOM) newPage();
  y = drawSectionTitle(
    pdf,
    "Courses & Clashes",
    "Course, type, credits, slots, venue, faculty — and what each course clashes with",
    y,
  );

  const drawTableHeader = () => {
    pdf.setFont("helvetica", "bold");
    let headerX = CONTENT_X;
    CLASH_REPORT_HEADERS.forEach((label, i) => {
      color(pdf, "setFillColor", THEME.panel);
      color(pdf, "setDrawColor", THEME.border);
      pdf.rect(headerX, y, CLASH_REPORT_COLUMNS[i], 8, "FD");
      color(pdf, "setTextColor", THEME.text);
      pdf.setFontSize(6.2);
      pdf.text(label, headerX + 1.2, y + 5.3);
      headerX += CLASH_REPORT_COLUMNS[i];
    });
    y += 8;
  };
  const continueTable = () => {
    newPage();
    y = drawSectionTitle(pdf, "Courses & Clashes (continued)", "Course details continue on this page", y);
    drawTableHeader();
  };
  drawTableHeader();

  for (let index = 0; index < courses.length; index++) {
    const item = courses[index];
    const clashCell = formatClashCell(clashByCourse.get(item.id));
    const values = [
      item.code,
      item.title,
      typeLabels[item.type] || item.type || "Theory",
      item.credits || "0",
      item.slots.join(", "),
      item.venue || "TBA",
      item.faculty || "TBA",
      clashCell,
    ];
    const wrapped = values.map((value, i) => wrap(pdf, value, CLASH_REPORT_COLUMNS[i] - 2.5, 5.8));
    const lineCount = Math.max(1, ...wrapped.map((lines) => lines.length));
    let lineOffset = 0;
    while (lineOffset < lineCount) {
      const availableLines = Math.floor((CONTENT_BOTTOM - y - 3) / 3.25);
      if (availableLines < 1) {
        continueTable();
        continue;
      }
      const chunkLines = Math.min(lineCount - lineOffset, availableLines);
      const rowHeight = Math.max(lineCount === 1 ? 9.5 : 0, chunkLines * 3.25 + 3);
      color(pdf, "setFillColor", index % 2 === 0 ? THEME.surface : THEME.panel);
      color(pdf, "setDrawColor", THEME.border);
      pdf.rect(CONTENT_X, y, CONTENT_W, rowHeight, "FD");
      let cellX = CONTENT_X;
      wrapped.forEach((lines, i) => {
        const slice = lines.slice(lineOffset, lineOffset + chunkLines);
        if (slice.length) {
          color(
            pdf,
            "setTextColor",
            i === 0
              ? COLOR_HEX_MAP[item.color] || THEME.accent
              : i === CLASH_COLUMN
                ? clashCell === "-"
                  ? THEME.muted
                  : THEME.clash
                : THEME.text,
          );
          pdf.setFont("helvetica", i === 0 ? "bold" : "normal");
          pdf.setFontSize(5.8);
          pdf.text(slice, cellX + 1.2, y + 3.8, { lineHeightFactor: 1.1 });
        }
        cellX += CLASH_REPORT_COLUMNS[i];
      });
      y += rowHeight;
      lineOffset += chunkLines;
      if (lineOffset < lineCount) continueTable();
    }
  }

  if (courses.length === 0) {
    color(pdf, "setTextColor", THEME.muted);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    pdf.text("No courses on this plan yet.", CONTENT_X, y + 4);
  }

  // The weekly curriculum: the same courses, read as a week. This is the
  // section a student copies from — one row per class block, day-major.
  const sessions = buildCurriculumSessions(courses, schema);
  if (sessions.length > 0) {
    if (y + 40 > CONTENT_BOTTOM) newPage();
    y = drawSectionTitle(
      pdf,
      "Weekly Curriculum",
      "Every class of this plan, expanded to the day and clock time it meets - read down a day to copy the week",
      y,
    );

    const drawCurriculumHeader = () => {
      pdf.setFont("helvetica", "bold");
      let headerX = CONTENT_X;
      CURRICULUM_HEADERS.forEach((label, i) => {
        color(pdf, "setFillColor", THEME.panel);
        color(pdf, "setDrawColor", THEME.border);
        pdf.rect(headerX, y, CURRICULUM_COLUMNS[i], 8, "FD");
        color(pdf, "setTextColor", THEME.text);
        pdf.setFontSize(6.2);
        pdf.text(label, headerX + 1.2, y + 5.3);
        headerX += CURRICULUM_COLUMNS[i];
      });
      y += 8;
    };
    const continueCurriculum = () => {
      newPage();
      y = drawSectionTitle(pdf, "Weekly Curriculum (continued)", "Class sessions continue on this page", y);
      drawCurriculumHeader();
    };
    drawCurriculumHeader();

    // The CODE cell wears the course's own colour, the same one the course
    // row above wears, so the two tables cross-reference by colour.
    const colorByCode = new Map(courses.map((course) => [course.code, course.color]));

    for (let index = 0; index < sessions.length; index++) {
      const session = sessions[index];
      const values = [
        session.day,
        `${formatMinutesOfDay(session.startMin)}-${formatMinutesOfDay(session.endMin)}`,
        session.type === "lab" ? "Lab" : "Theory",
        session.code,
        session.title,
        session.venue,
        session.faculty,
      ];
      const wrapped = values.map((value, i) => wrap(pdf, value, CURRICULUM_COLUMNS[i] - 2.5, 5.8));
      const lineCount = Math.max(1, ...wrapped.map((lines) => lines.length));
      let lineOffset = 0;
      while (lineOffset < lineCount) {
        const availableLines = Math.floor((CONTENT_BOTTOM - y - 3) / 3.25);
        if (availableLines < 1) {
          continueCurriculum();
          continue;
        }
        const chunkLines = Math.min(lineCount - lineOffset, availableLines);
        const rowHeight = Math.max(lineCount === 1 ? 9.5 : 0, chunkLines * 3.25 + 3);
        // Zebra stripes run by day, so one day reads as one band.
        const dayBand = session.dayOrder % 2 === 0;
        color(pdf, "setFillColor", dayBand ? THEME.surface : THEME.panel);
        color(pdf, "setDrawColor", THEME.border);
        pdf.rect(CONTENT_X, y, CONTENT_W, rowHeight, "FD");
        let cellX = CONTENT_X;
        wrapped.forEach((lines, i) => {
          const slice = lines.slice(lineOffset, lineOffset + chunkLines);
          if (slice.length) {
            color(
              pdf,
              "setTextColor",
              i === 0
                ? THEME.accent
                : i === 3
                  ? COLOR_HEX_MAP[colorByCode.get(session.code) || ""] || THEME.accent
                  : THEME.text,
            );
            pdf.setFont("helvetica", i === 0 || i === 3 ? "bold" : "normal");
            pdf.setFontSize(5.8);
            pdf.text(slice, cellX + 1.2, y + 3.8, { lineHeightFactor: 1.1 });
          }
          cellX += CURRICULUM_COLUMNS[i];
        });
        y += rowHeight;
        lineOffset += chunkLines;
        if (lineOffset < lineCount) continueCurriculum();
      }
    }
  }

  return pdf.output("arraybuffer");
}

/**
 * Build the clash report and hand it to the browser as a download.
 *
 * The filename follows the other exports' convention
 * (`<clean plan name>_FFCS_Clash_Report.pdf`); jsPDF is imported lazily by
 * `createClashReportPdf`, so merely importing this module is safe on the
 * server and in workers.
 */
export async function downloadClashReportPdf(params: ClashReportParams): Promise<void> {
  const buffer = await createClashReportPdf(params);
  const blob = new Blob([buffer], { type: "application/pdf" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  const cleanName = (params.planName || "Timetable").replace(/[^a-zA-Z0-9_-]/g, "_");
  link.href = url;
  link.download = `${cleanName}_FFCS_Clash_Report.pdf`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL?.(url), 2000);
}
