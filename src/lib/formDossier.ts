/**
 * The print-friendly FFCS dossier: a monochrome, application-form style
 * A4 portrait PDF of the current plan.
 *
 * Paper is not a screen. The screen dossier earns its colour (course hues,
 * sentiment badges, gradient banners) because it is read on a display; a
 * document that gets printed on a campus printer, stapled, or photocopied
 * needs the opposite — black ink on white stock, hairline boxes, labelled
 * fields, numbered sections, and nothing that only survives in colour. This
 * module is that document: the layout language of a passport application
 * (a bordered field block up top, ruled tables below, `Page X of Y` in the
 * footer) applied to the plan.
 *
 * Like `exportClashReport`, it is vector end to end — real text and real
 * rules drawn with jsPDF, not a screenshot — so the output stays crisp at
 * any zoom, is searchable, and lands page breaks between rows instead of
 * through them. The drawing recipe (wrap → chunk → continue-on-next-page)
 * is the one `portraitDossier` established; the palette here is the point
 * of the module and is exported so tests can prove every colour is gray.
 *
 * Import-light by design: types and pure data maps only, jsPDF pulled
 * lazily on first use so a planner session that never exports never pays
 * for the library.
 */
