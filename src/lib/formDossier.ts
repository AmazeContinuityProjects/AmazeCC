/**
 * Reduce a string to what jsPDF's standard fonts can actually draw.
 *
 * Helvetica ships as WinAnsi: Latin-1 prints, emoji and CJK do not, and the
 * odd typographic punctuation (en dash, curly quotes, ★) renders as garbage
 * or a lost glyph — `ffcsClashPairs` documents the same hazard. Common
 * punctuation folds to its ASCII twin first so names keep their shape,
 * then anything outside printable ASCII + Latin-1 is dropped.
 */
export function printSafe(value: string): string {
  const folded = value
    .replace(/[\u2013\u2014\u2212]/g, "-")
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/\u2026/g, "...")
    .replace(/[\u2022\u25cf\u25aa]/g, "-")
    .replace(/[\u2605\u2606]/g, "*")
    .replace(/[\u2713\u2714]/g, "v")
    .replace(/[\u2717\u2718]/g, "x")
    .replace(/\u00a0/g, " ");
  return folded.replace(/[^\u0020-\u007e\u00a0-\u00ff]/g, "");
}

function rgb(hex: string): [number, number, number] {
  const value = hex.replace("#", "");
  return [parseInt(value.slice(0, 2), 16), parseInt(value.slice(2, 4), 16), parseInt(value.slice(4, 6), 16)];
}

function color(pdf: jsPDF, method: "setTextColor" | "setDrawColor" | "setFillColor", hex: string) {
  pdf[method](...rgb(hex));
}

function wrap(pdf: jsPDF, value: string, width: number, size: number): string[] {
  pdf.setFontSize(size);
  return pdf.splitTextToSize(printSafe(value) || "-", width) as string[];
}

/** Shrink a single-line value until it fits its box, form-field style. */
function fitOneLine(pdf: jsPDF, value: string, width: number, startSize: number, minSize: number): string[] {
  let size = startSize;
  for (;;) {
    pdf.setFontSize(size);
    const lines = pdf.splitTextToSize(printSafe(value) || "-", width) as string[];
    if (lines.length <= 1 || size <= minSize) return [lines[0]];
    size -= 0.5;
  }
}

/** Merge the picked courses by code: one register row per course. */
function groupCourses(courses: AddedCourse[]) {
  const groups = new Map<string, AddedCourse & { batches: string[] }>();
  for (const course of courses) {
    const current = groups.get(course.code);
    if (!current) {
      groups.set(course.code, {
        ...course,
        slots: [...course.slots],
        batches: (course.batch || "")
          .split(",")
          .map((x) => x.trim())
          .filter(Boolean),
      });
      continue;
    }
    if (course.faculty && !current.faculty.includes(course.faculty))
      current.faculty = [current.faculty, course.faculty].filter(Boolean).join(" / ");
    if (course.venue && !current.venue.includes(course.venue))
      current.venue = [current.venue, course.venue].filter(Boolean).join(" / ");
    if (course.type && !current.type.includes(course.type))
      current.type = [current.type, course.type].filter(Boolean).join(" + ");
    for (const slot of course.slots) if (!current.slots.includes(slot)) current.slots.push(slot);
    for (const batch of (course.batch || "")
      .split(",")
      .map((x) => x.trim())
      .filter(Boolean))
      if (!current.batches.includes(batch)) current.batches.push(batch);
    current.credits = String((parseFloat(current.credits || "0") || 0) + (parseFloat(course.credits || "0") || 0));
  }
  return [...groups.values()];
}

/** White stock, printed frame, nothing else — one per page. */
function drawPageChrome(pdf: jsPDF) {
  color(pdf, "setFillColor", FORM_INK.paper);
  pdf.rect(0, 0, PAGE_W, PAGE_H, "F");
  color(pdf, "setDrawColor", FORM_INK.ink);
  pdf.setLineWidth(0.3);
  pdf.rect(FRAME_INSET, FRAME_INSET, PAGE_W - FRAME_INSET * 2, PAGE_H - FRAME_INSET * 2, "S");
}

function addPage(pdf: jsPDF, pageNumber: number) {
  if (pageNumber > 1) pdf.addPage("a4", "portrait");
  drawPageChrome(pdf);
}

/**
 * A numbered section heading: `2. COURSE REGISTER`, a one-line gloss, and
 * a full-width rule — the way a form breaks itself into parts.
 */
function drawSectionTitle(pdf: jsPDF, number: number, title: string, subtitle: string, y: number): number {
  color(pdf, "setTextColor", FORM_INK.ink);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(10.5);
  pdf.text(printSafe(`${number}. ${title}`), CONTENT_X, y);
  color(pdf, "setTextColor", FORM_INK.mid);
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(6.5);
  pdf.text(printSafe(subtitle), CONTENT_X, y + 4.3);
  color(pdf, "setDrawColor", FORM_INK.ink);
  pdf.setLineWidth(0.35);
  pdf.line(CONTENT_X, y + 6.8, CONTENT_X + CONTENT_W, y + 6.8);
  return y + 11.5;
}

/** Repeating section heading after a page break. */
function continueSection(pdf: jsPDF, number: number, title: string, subtitle: string, y: number): number {
  return drawSectionTitle(pdf, number, `${title} (CONTINUED)`, subtitle, y);
}

function drawTableHeader(pdf: jsPDF, columns: readonly number[], headers: readonly string[], y: number): number {
  pdf.setFont("helvetica", "bold");
  let x = CONTENT_X;
  headers.forEach((label, i) => {
    color(pdf, "setFillColor", FORM_INK.band);
    color(pdf, "setDrawColor", FORM_INK.ink);
    pdf.setLineWidth(0.25);
    pdf.rect(x, y, columns[i], 8, "FD");
    color(pdf, "setTextColor", FORM_INK.ink);
    pdf.setFontSize(6);
    pdf.text(printSafe(label), x + 1.5, y + 5.3);
    x += columns[i];
  });
  return y + 8;
}

interface ChunkedTableOptions {
  columns: readonly number[];
  headers: readonly string[];
  /** One array of raw cell values per logical row. */
  rows: string[][];
  /** Columns drawn bold (identity columns: codes, names). */
  boldColumns?: readonly number[];
  cellFont?: number;
  lineHeight?: number;
  /** Called after a page break: draws the continued heading + table header. */
  onContinue: () => number;
}

/**
 * The shared table renderer: wrap every cell, chunk rows across pages, and
 * never split a row — a table row that straddles a page edge is the classic
 * sign of a screen export printed to paper.
 */
function drawChunkedTable(pdf: jsPDF, startY: number, options: ChunkedTableOptions): number {
  const { columns, headers, rows, boldColumns = [], cellFont = 5.8, lineHeight = 3.25, onContinue } = options;
  let y = drawTableHeader(pdf, columns, headers, startY);

  for (let index = 0; index < rows.length; index++) {
    const wrapped = rows[index].map((value, i) => wrap(pdf, value, columns[i] - 2.5, cellFont));
    const lineCount = Math.max(1, ...wrapped.map((lines) => lines.length));
    let lineOffset = 0;
    while (lineOffset < lineCount) {
      const availableLines = Math.floor((CONTENT_BOTTOM - y - 3) / lineHeight);
      if (availableLines < 1) {
        y = onContinue();
        continue;
      }
      const chunkLines = Math.min(lineCount - lineOffset, availableLines);
      const rowHeight = Math.max(lineCount === 1 ? 9 : 0, chunkLines * lineHeight + 3);
      color(pdf, "setFillColor", FORM_INK.paper);
      color(pdf, "setDrawColor", FORM_INK.ink);
      pdf.setLineWidth(0.2);
      pdf.rect(CONTENT_X, y, CONTENT_W, rowHeight, "FD");
      let cellX = CONTENT_X;
      wrapped.forEach((lines, i) => {
        const slice = lines.slice(lineOffset, lineOffset + chunkLines);
        if (slice.length) {
          color(pdf, "setTextColor", FORM_INK.ink);
          pdf.setFont("helvetica", boldColumns.includes(i) ? "bold" : "normal");
          pdf.setFontSize(cellFont);
          pdf.text(slice, cellX + 1.5, y + 3.8, { lineHeightFactor: 1.1 });
        }
        cellX += columns[i];
      });
      y += rowHeight;
      lineOffset += chunkLines;
      if (lineOffset < lineCount) y = onContinue();
    }
  }
  return y;
}

/**
 * The form header: title, then a bordered block of labelled fields — the
 * passport-application applicant box, holding the plan's vital statistics.
 */
function drawFormHeader(
  pdf: jsPDF,
  params: PrintDossierParams,
  groups: ReturnType<typeof groupCourses>,
  credits: number,
  clashPairs: number,
  y: number,
): number {
  const title = params.timetableName || "Timetable";
  color(pdf, "setTextColor", FORM_INK.ink);
  pdf.setFont("helvetica", "bold");
  const titleLines = fitOneLine(pdf, `FFCS REGISTRATION DOSSIER - ${title}`, CONTENT_W - 10, 13, 9);
  pdf.text(titleLines[0], PAGE_W / 2, y + 7, { align: "center" });
  color(pdf, "setDrawColor", FORM_INK.ink);
  pdf.setLineWidth(0.5);
  pdf.line(CONTENT_X, y + 10.5, CONTENT_X + CONTENT_W, y + 10.5);

  const boxTop = y + 13.5;
  const rowH = 13;
  const cols = [74, 52, 52];
  const generated = (params.generatedAt ?? new Date()).toLocaleDateString("en-GB");
  const fields: [string, string][][] = [
    [
      ["PLAN NAME", title],
      ["INSTITUTE", "VIT Chennai"],
      ["GENERATED ON", generated],
    ],
    [
      ["COURSES ENROLLED", String(groups.length)],
      ["TOTAL CREDITS", String(credits)],
      [
        "CLASH STATUS",
        clashPairs > 0 ? `${clashPairs} clash${clashPairs === 1 ? "" : "es"} detected` : "None - all fit",
      ],
    ],
  ];

  // Field box: outer rule, then the grid of cells inside it.
  color(pdf, "setDrawColor", FORM_INK.ink);
  pdf.setLineWidth(0.35);
  pdf.rect(CONTENT_X, boxTop, CONTENT_W, rowH * 2, "S");
  pdf.setLineWidth(0.2);
  pdf.line(CONTENT_X, boxTop + rowH, CONTENT_X + CONTENT_W, boxTop + rowH);
  let x = CONTENT_X + cols[0];
  pdf.line(x, boxTop, x, boxTop + rowH * 2);
  x = CONTENT_X + cols[0] + cols[1];
  pdf.line(x, boxTop, x, boxTop + rowH * 2);

  fields.forEach((row, rowIndex) => {
    let cellX = CONTENT_X;
    row.forEach(([label, rawValue], colIndex) => {
      const width = cols[colIndex];
      color(pdf, "setTextColor", FORM_INK.dark);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(5.5);
      pdf.text(printSafe(label), cellX + 2.5, boxTop + rowIndex * rowH + 5, { charSpace: 0.3 });
      color(pdf, "setTextColor", FORM_INK.ink);
      const value = fitOneLine(pdf, rawValue, width - 5, 9, 6.5);
      pdf.setFont("helvetica", "bold");
      pdf.text(value[0], cellX + 2.5, boxTop + rowIndex * rowH + 10.5);
      cellX += width;
    });
  });

  return boxTop + rowH * 2 + 8;
}

/** The week as a ruled grid: gray headers, black hairlines, no course hues. */
function drawScheduleGrid(pdf: jsPDF, params: PrintDossierParams, y: number): number {
  const days = params.days?.length ? params.days : DEFAULT_DAYS;
  const theoryPeriods = ensureLunchPeriod(params.theoryPeriods);
  const labPeriods = ensureLunchPeriod(params.labPeriods);
  const periodCount = Math.max(theoryPeriods.length, labPeriods.length);
  if (!periodCount) {
    color(pdf, "setTextColor", FORM_INK.mid);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    pdf.text("No timetable periods were provided.", CONTENT_X, y + 6);
    return y + 15;
  }

  const dayW = 12;
  const colW = (CONTENT_W - dayW) / periodCount;
  const headerH = 13;
  const rowH = Math.min(12.5, Math.max(9.2, (CONTENT_BOTTOM - y - 34) / days.length));
  const lunchIndex = theoryPeriods.findIndex((period) => period?.lunch);

  // Header row: DAY column plus one cell per period.
  color(pdf, "setFillColor", FORM_INK.band);
  color(pdf, "setDrawColor", FORM_INK.ink);
  color(pdf, "setTextColor", FORM_INK.ink);
  pdf.setLineWidth(0.25);
  pdf.rect(CONTENT_X, y, dayW, headerH, "FD");
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(5.8);
  pdf.text("DAY", CONTENT_X + dayW / 2, y + 7.5, { align: "center" });
  for (let col = 0; col < periodCount; col++) {
    const x = CONTENT_X + dayW + col * colW;
    const isLunch = Boolean(theoryPeriods[col]?.lunch);
    color(pdf, "setFillColor", isLunch ? FORM_INK.panel : FORM_INK.band);
    color(pdf, "setDrawColor", FORM_INK.ink);
    pdf.rect(x, y, colW, headerH, "FD");
    color(pdf, "setTextColor", FORM_INK.ink);
    if (isLunch) {
      pdf.setFontSize(5.6);
      pdf.text("LUNCH", x + colW / 2, y + 5.5, { align: "center" });
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(4.2);
      pdf.text("1:20-2:00", x + colW / 2, y + 10.2, { align: "center" });
      pdf.setFont("helvetica", "bold");
    } else {
      pdf.setFontSize(6.1);
      pdf.text(`P${lunchIndex >= 0 && col > lunchIndex ? col : col + 1}`, x + colW / 2, y + 5.5, { align: "center" });
      color(pdf, "setTextColor", FORM_INK.mid);
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(5);
      pdf.text(theoryPeriods[col]?.start || "", x + colW / 2, y + 10.2, {
        align: "center",
        maxWidth: colW - 1.2,
      });
      pdf.setFont("helvetica", "bold");
    }
  }

  days.forEach((day, row) => {
    const rowY = y + headerH + row * rowH;
    color(pdf, "setFillColor", FORM_INK.panel);
    color(pdf, "setDrawColor", FORM_INK.ink);
    color(pdf, "setTextColor", FORM_INK.ink);
    pdf.setLineWidth(0.2);
    pdf.rect(CONTENT_X, rowY, dayW, rowH, "FD");
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(5.2);
    pdf.text(day.name.slice(0, 3).toUpperCase(), CONTENT_X + dayW / 2, rowY + rowH / 2 + 1.5, { align: "center" });

    for (let col = 0; col < periodCount; col++) {
      const x = CONTENT_X + dayW + col * colW;
      const theoryPeriod = theoryPeriods[col];
      const theorySlot = theoryPeriod?.days?.[day.id];
      const labSlot = labPeriods[col]?.days?.[day.id];
      if (theoryPeriod?.lunch) {
        if (row === 0) {
          const lunchY = y + headerH;
          const lunchH = days.length * rowH;
          color(pdf, "setFillColor", FORM_INK.panel);
          color(pdf, "setDrawColor", FORM_INK.ink);
          pdf.rect(x, lunchY, colW, lunchH, "FD");
          color(pdf, "setTextColor", FORM_INK.ink);
          pdf.setFont("helvetica", "bold");
          pdf.setFontSize(7);
          pdf.text("LUNCH", x + colW / 2, lunchY + lunchH / 2 - 3, { align: "center", angle: 90 });
          pdf.setFont("helvetica", "normal");
          pdf.setFontSize(5);
          pdf.text("1:20-2:00", x + colW / 2, lunchY + lunchH / 2 + 16, { align: "center", angle: 90 });
        }
        continue;
      }
      color(pdf, "setFillColor", FORM_INK.paper);
      color(pdf, "setDrawColor", FORM_INK.ink);
      pdf.rect(x, rowY, colW, rowH, "FD");

      const theoryCourse = theorySlot ? params.courses.find((item) => item.slots.includes(theorySlot)) : undefined;
      const labCourse = labSlot ? params.courses.find((item) => item.slots.includes(labSlot)) : undefined;
      const halves = [
        { slot: theorySlot, course: theoryCourse },
        { slot: labSlot, course: labCourse },
      ].filter((half) => half.slot || half.course);
      halves.slice(0, 2).forEach((half, halfIndex) => {
        const halfHeight = rowH / halves.length;
        const centerY = rowY + halfIndex * halfHeight + halfHeight / 2;
        color(pdf, "setTextColor", half.course ? FORM_INK.ink : FORM_INK.mid);
        pdf.setFont("helvetica", half.course ? "bold" : "normal");
        const codeSize = Math.min(5.4, Math.max(4.6, colW * 0.32));
        pdf.setFontSize(codeSize);
        pdf.text(printSafe(half.course?.code || half.slot || ""), x + colW / 2, centerY - 0.55, {
          align: "center",
          maxWidth: colW - 1.2,
        });
        if (half.course && half.slot) {
          color(pdf, "setTextColor", FORM_INK.mid);
          pdf.setFont("helvetica", "normal");
          pdf.setFontSize(4.4);
          pdf.text(printSafe(half.slot), x + colW / 2, centerY + 1.65, { align: "center", maxWidth: colW - 1.2 });
        }
      });
    }
  });

  return y + headerH + days.length * rowH;
}

/** Faculty rows: name, courses, Vitfac win rate, metric averages — all text. */
function buildFacultyRows(courses: AddedCourse[]): string[][] {
  interface Entry {
    name: string;
    employeeId?: string;
    codes: string[];
  }
  const byKey = new Map<string, Entry>();
  for (const course of courses) {
    const names = (course.faculty || "")
      .split(/\s*\/\s*/)
      .map((s) => s.trim())
      .filter(Boolean);
    if (names.length === 0) names.push("TBA");
    const ids = (course.employeeId || "")
      .split(/\s*\/\s*/)
      .map((s) => s.trim())
      .filter(Boolean);
    names.forEach((name, i) => {
      const employeeId = ids[i] || (ids.length === 1 ? ids[0] : undefined);
      const key = `${name.toLowerCase()}|${employeeId || ""}`;
      const entry = byKey.get(key);
      if (!entry) byKey.set(key, { name, employeeId, codes: [course.code] });
      else if (!entry.codes.includes(course.code)) entry.codes.push(course.code);
    });
  }

  return [...byKey.values()].map((entry) => {
    const review = getFacultyReview({ employeeId: entry.employeeId, name: entry.name });
    const rated = review && review.reviews > 0;
    const winRate = rated ? `${review.wPct}% (${review.reviews} reviews)` : "Unreviewed";
    const metrics =
      rated && review.metrics
        ? `Teach ${review.metrics.lecture.toFixed(1)} | DA ${review.metrics.da.toFixed(1)} | Vibe ${review.metrics.vibe.toFixed(1)}`
        : "-";
    return [entry.name, entry.codes.join(", "), winRate, metrics];
  });
}

/** One line per course component: current faculty, then who can take over. */
function buildDropInRows(params: PrintDossierParams): string[][] {
  const halves = expandCourseHalves(params.courses);
  return halves.map((half) => {
    const alternatives = sameSlotFacultyAlternatives(
      half.code,
      half.slots,
      { faculty: half.faculty, employeeId: half.employeeId },
      params.masterCourses ?? [],
    );
    const described = alternatives.slice(0, 6).map((alt) => {
      const review = getFacultyReview({ employeeId: alt.ERP_ID, name: alt.FACULTY });
      const rate = review && review.reviews > 0 ? `, ${review.wPct}% W` : "";
      return `${alt.FACULTY || "TBA"} (${alt.ROOM || "TBA"}${rate})`;
    });
    if (described.length > 6) described.push(`+${alternatives.length - 6} more`);
    const list = described.length ? described.join("; ") : "No matching faculty in the catalog";
    return [half.code, half.slots.join("+"), half.faculty || "TBA", list];
  });
}

/**
 * Build the print-friendly dossier as an A4 portrait PDF.
 *
 * Works for any plan the planner can hold — hand-built or generated — and
 * degrades honestly: no catalog loaded says so, Vitfac off omits the
 * assessment section entirely rather than printing empty scorecards.
 */
export async function createPrintDossierPdf(params: PrintDossierParams): Promise<ArrayBuffer> {
  const { jsPDF } = await import("jspdf");
  const schema = params.schema ?? getTimetableSchema();
  const groups = groupCourses(params.courses);
  const credits = params.totalCredits ?? groups.reduce((sum, item) => sum + (parseFloat(item.credits || "0") || 0), 0);
  const clashPairs = courseClashPairCount(params.courses, schema);
  const showVitfac = isVitfacIntegrationEnabled();

  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4", compress: true });
  pdf.setProperties({
    title: `${params.timetableName || "Timetable"} - FFCS Print Dossier`,
    subject: "Print-friendly registration dossier",
    creator: "AmazeCC",
  });

  let pageNumber = 1;
  let y = CONTENT_TOP;
  addPage(pdf, pageNumber);
  const newPage = () => {
    pageNumber += 1;
    addPage(pdf, pageNumber);
    y = CONTENT_TOP;
  };

  y = drawFormHeader(pdf, params, groups, credits, clashPairs, y);

  // 1. The week, as a ruled grid. The break check runs before the heading
  // so a squeezed page never strands "1. WEEKLY CLASS SCHEDULE" alone.
  const gridHeight = 13 + (params.days?.length || DEFAULT_DAYS.length) * 12.5 + 4;
  if (y + 11.5 + gridHeight > CONTENT_BOTTOM) newPage();
  y = drawSectionTitle(pdf, 1, "WEEKLY CLASS SCHEDULE", "Periods Monday to Friday - read across a row for one day", y);
  y = drawScheduleGrid(pdf, params, y) + 7;

  // 2. The register: one row per enrolled course.
  if (y + 32 > CONTENT_BOTTOM) newPage();
  y = drawSectionTitle(pdf, 2, "COURSE REGISTER", "Course, registration type, credits, slots, venue and faculty", y);
  y = drawChunkedTable(pdf, y, {
    columns: PRINT_COURSE_COLUMNS,
    headers: PRINT_COURSE_HEADERS,
    boldColumns: [0],
    rows: groups.map((item) => [
      item.code,
      item.title || item.code,
      typeLabels[item.type] || item.type || "Theory",
      item.credits || "0",
      item.slots.join(", "),
      item.venue || "TBA",
      item.faculty || "TBA",
    ]),
    onContinue: () => {
      newPage();
      const headingY = continueSection(pdf, 2, "COURSE REGISTER", "Course details continue on this page", CONTENT_TOP);
      return drawTableHeader(pdf, PRINT_COURSE_COLUMNS, PRINT_COURSE_HEADERS, headingY);
    },
  });
  if (groups.length === 0) {
    color(pdf, "setTextColor", FORM_INK.mid);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(7.5);
    pdf.text("No courses on this plan yet.", CONTENT_X, y + 4);
    y += 10;
  }
  y += 6;

  // 3. Faculty assessment — only when Vitfac can actually answer for it.
  if (showVitfac) {
    const facultyRows = buildFacultyRows(params.courses);
    if (facultyRows.length > 0) {
      if (y + 32 > CONTENT_BOTTOM) newPage();
      y = drawSectionTitle(
        pdf,
        3,
        "FACULTY ASSESSMENT",
        "Attached faculty with Vitfac win rate and metric averages",
        y,
      );
      y = drawChunkedTable(pdf, y, {
        columns: PRINT_FACULTY_COLUMNS,
        headers: PRINT_FACULTY_HEADERS,
        boldColumns: [0],
        rows: facultyRows,
        onContinue: () => {
          newPage();
          const headingY = continueSection(
            pdf,
            3,
            "FACULTY ASSESSMENT",
            "Faculty assessment continues on this page",
            CONTENT_TOP,
          );
          return drawTableHeader(pdf, PRINT_FACULTY_COLUMNS, PRINT_FACULTY_HEADERS, headingY);
        },
      });
      y += 6;
    }
  }

  // 4. Drop-in replacements: who to switch to when a target faculty fills.
  if (y + 32 > CONTENT_BOTTOM) newPage();
  y = drawSectionTitle(
    pdf,
    4,
    "DROP-IN REPLACEMENTS",
    "Same-slot alternatives from the master catalog if a target faculty fills up",
    y,
  );
  if (!params.masterCourses?.length) {
    color(pdf, "setTextColor", FORM_INK.mid);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(7.5);
    pdf.text("Load the master FFCS catalog to discover matching-slot alternatives.", CONTENT_X, y + 4);
    y += 10;
  } else {
    const dropInRows = buildDropInRows(params);
    y = drawChunkedTable(pdf, y, {
      columns: PRINT_DROPIN_COLUMNS,
      headers: PRINT_DROPIN_HEADERS,
      boldColumns: [0],
      rows: dropInRows,
      onContinue: () => {
        newPage();
        const headingY = continueSection(
          pdf,
          4,
          "DROP-IN REPLACEMENTS",
          "Drop-in alternatives continue on this page",
          CONTENT_TOP,
        );
        return drawTableHeader(pdf, PRINT_DROPIN_COLUMNS, PRINT_DROPIN_HEADERS, headingY);
      },
    });
  }

  // Running head + footer, written once the page count is known.
  const total = pdf.getNumberOfPages();
  const planName = printSafe(params.timetableName || "Timetable");
  for (let page = 1; page <= total; page++) {
    pdf.setPage(page);
    color(pdf, "setTextColor", FORM_INK.mid);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(6.5);
    pdf.text(CREDIT_LINE, CONTENT_X, FOOTER_Y);
    pdf.text(`Page ${page} of ${total}`, PAGE_W - CONTENT_X, FOOTER_Y, { align: "right" });
    if (page > 1) {
      pdf.setFontSize(6);
      pdf.text("FFCS REGISTRATION DOSSIER", CONTENT_X, 13.5);
      pdf.text(planName, PAGE_W - CONTENT_X, 13.5, { align: "right", maxWidth: 100 });
    }
  }

  return pdf.output("arraybuffer");
}

/**
 * Build the print-friendly dossier and hand it to the browser as a download.
 *
 * Filename follows the other exports' convention
 * (`<clean plan name>_FFCS_Print_Dossier.pdf`); jsPDF is imported lazily by
 * `createPrintDossierPdf`, so importing this module is safe on the server.
 */
export async function downloadPrintDossierPdf(params: PrintDossierParams): Promise<void> {
  const buffer = await createPrintDossierPdf(params);
  const blob = new Blob([buffer], { type: "application/pdf" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  const cleanName = (params.timetableName || "Timetable").replace(/[^a-zA-Z0-9_-]/g, "_");
  link.href = url;
  link.download = `${cleanName}_FFCS_Print_Dossier.pdf`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL?.(url), 2000);
}
